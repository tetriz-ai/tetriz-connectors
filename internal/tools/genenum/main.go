// Command genenum writes database and JSON helpers for protobuf enums: the
// enum is stored and marshalled as its value name (for example
// "BITBUCKET_REPO_STATUS_ACTIVE") instead of its number. Run it through the
// //go:generate line at the top of a generated .pb.go file:
//
//	//go:generate go run github.com/tetriz-ai/tetriz-connectors/internal/tools/genenum -types=A,B
//
// It writes <file>.pb.sql.gen.go beside the .pb.go file named by GOFILE.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
	"text/template"
)

var tmpl = template.Must(template.New("enum").Parse(`// Code generated by genenum. DO NOT EDIT.

package {{.Package}}

import (
	"database/sql/driver"
	"encoding/json"
	"fmt"
)
{{range .Types}}
// Value stores {{.}} as its value name.
func (p {{.}}) Value() (driver.Value, error) {
	return p.String(), nil
}

// Scan reads {{.}} from its value name.
func (p *{{.}}) Scan(value interface{}) error {
	val, ok := value.(string)
	if !ok {
		return fmt.Errorf("type conversion to string failed, src: %T", val)
	}

	valInt, ok := {{.}}_value[val]
	if !ok {
		return fmt.Errorf("unexpected {{.}} value: %s", val)
	}
	*p = {{.}}(valInt)
	return nil
}

// MarshalJSON writes {{.}} as its value name.
func (x {{.}}) MarshalJSON() ([]byte, error) {
	return json.Marshal(x.String())
}

// UnmarshalJSON reads {{.}} from its value name. An unknown name reads as
// the zero value.
func (x *{{.}}) UnmarshalJSON(b []byte) error {
	var val string
	err := json.Unmarshal(b, &val)
	if err != nil {
		return err
	}
	*x = {{.}}({{.}}_value[val])
	return nil
}
{{end}}`))

func main() {
	types := flag.String("types", "", "comma-separated enum type names")
	flag.Parse()
	goFile, pkg := os.Getenv("GOFILE"), os.Getenv("GOPACKAGE")
	if goFile == "" || pkg == "" || *types == "" {
		log.Fatal("genenum: run through go generate with -types")
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]any{"Package": pkg, "Types": strings.Split(*types, ",")}); err != nil {
		log.Fatal(err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	name := strings.TrimSuffix(goFile, ".go") + ".sql.gen.go"
	if err := os.WriteFile(name, out, 0o600); err != nil {
		log.Fatal(fmt.Errorf("genenum: write %s: %w", name, err))
	}
}
